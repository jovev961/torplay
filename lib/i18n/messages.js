export function macedonianMessage(message) {
  if (MK_MESSAGES[message]) return MK_MESSAGES[message];
  for (const [pattern, replacement] of MK_PATTERNS) {
    if (pattern.test(message)) return message.replace(pattern, replacement);
  }
  return message;
}
